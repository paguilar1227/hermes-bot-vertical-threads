import { build } from 'esbuild'
import { createServer } from 'node:http'
import { resolve } from 'node:path'
import { chromium, expect } from '@playwright/test'

const bundle = await build({ entryPoints: ['tests/plugin-fixture.tsx'], bundle: true, write: false, format: 'iife', jsx: 'automatic', alias: { '@hermes/plugin-sdk': resolve('tests/sdk-fixture.tsx') } })
const server = createServer((request, response) => {
  response.setHeader('Content-Type', request.url === '/fixture.js' ? 'text/javascript' : 'text/html')
  response.end(request.url === '/fixture.js' ? bundle.outputFiles[0].contents : '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Plugin contract test host</title><style>body{background:#202c31;color:#e7eeed;font:14px system-ui}aside{display:flex;gap:20px;padding:14px}output{font-size:11px}</style><div id="root"></div><script src="/fixture.js"></script></html>')
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
let browser
try {
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true })
  const page = await browser.newPage({ viewport: { width: 1240, height: 860 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(`http://127.0.0.1:${server.address().port}`)
  const bots = page.getByRole('button', { name: /assistant (This device|Remote host)/ })
  await expect(bots).toHaveCount(2)
  await bots.filter({ hasText: 'This device' }).click()
  await page.getByRole('button', { name: 'Release plan', exact: true }).click()
  await expect(page.getByLabel('Opened session')).toContainText('local:local-session')
  await bots.filter({ hasText: 'Remote host' }).click()
  await page.getByRole('button', { name: 'Remote plan', exact: true }).click()
  await expect(page.getByLabel('Opened session')).toContainText('remote:remote-session')
  await page.getByRole('region', { name: 'assistant threads', exact: true }).first().getByRole('button', { name: '+ New thread' }).click()
  await expect(page.getByLabel('Opened session')).toContainText('local:new-stored')
  await page.getByRole('button', { name: /Release Team.*2 members/ }).click()
  const team = page.getByRole('region', { name: 'Release Team threads', exact: true })
  await team.getByRole('button', { name: 'Monday release', exact: true }).click()
  await expect(page.getByRole('log')).toContainText('Monday release')
  await page.getByRole('textbox', { name: 'Message the team' }).fill('Ready to deploy')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByLabel('Last send')).toHaveText('local/assistant:team:existing-team-thread:Ready to deploy')
  await expect(page.getByRole('log')).toContainText('Ready to deploy')
  await team.getByRole('button', { name: '+ New thread' }).click()
  const chats = page.getByRole('textbox', { name: 'Message the team' })
  await chats.last().fill('Separate conversation')
  await page.getByRole('button', { name: 'Send', exact: true }).last().click()
  await expect(page.getByLabel('Last send')).toContainText('Separate conversation')
  await expect(page.getByRole('log').last()).not.toContainText('Monday release')
  await page.getByRole('button', { name: /Review Team.*2 members/ }).click()
  const review = page.getByRole('region', { name: 'Review Team threads', exact: true })
  await expect(review.getByRole('button', { name: 'QA checklist', exact: true })).toBeVisible()
  await expect(review.getByRole('button', { name: 'Monday release', exact: true })).toHaveCount(0)
  await review.getByRole('button', { name: 'QA checklist', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Message the team' })).toHaveCount(3)
  const reviewWorkspace = page.getByRole('region', { name: 'Review Team: QA checklist', exact: true })
  await reviewWorkspace.getByRole('textbox', { name: 'Message the team' }).fill('Review-only message')
  await reviewWorkspace.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByLabel('Last send')).toHaveText('local/reviewer:team:existing-team-thread:Review-only message')
  await expect(page.getByRole('log').first()).not.toContainText('Review-only message')
  await page.getByRole('button', { name: 'Delay next create' }).click()
  await page.getByRole('region', { name: 'assistant threads', exact: true }).first().getByRole('button', { name: '+ New thread' }).click()
  await expect(page.getByLabel('Pending create')).toHaveText('waiting')
  await page.getByRole('button', { name: 'Disable plugin' }).click()
  await page.getByRole('button', { name: 'Finish create' }).click()
  await expect(page.getByLabel('Pending create')).toHaveText('released')
  await expect(page.getByLabel('Opened session')).toHaveText('')
  await expect(page.getByRole('region', { name: 'Vertical Threads', exact: true })).toHaveCount(0)
  await expect(page.getByRole('log')).toHaveCount(0)
  expect(errors).toEqual([])
  console.log('Distributable plugin passed: public-SDK load, source-qualified bot navigation, new stored session, team history/send with thread identity, isolated new thread, and disable cleanup.')
} finally { await browser?.close(); server.close() }
